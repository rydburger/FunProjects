// =========================================================
// Error Correction Zoo Tycoon — zoo placards.
//
// The placard is the zoo's encyclopedia entry: science only, no game
// fluff. The written part (summary, facts, origin, lab history) lives
// in zoo-data.js; the parameters are computed here from the checks
// themselves (Stabilizer.analyzeChecks), so a player-built code gets
// the same computed section as a textbook one.
//
// DOM-free: returns HTML strings. Browser: load after ../stabilizer.js;
// exposes `window.Placard`. Node: require("./placard.js").
// =========================================================
(function (root) {
  var isNode = typeof module !== "undefined" && module.exports;
  var S = isNode ? require("../stabilizer.js") : root.Stabilizer;

  var ZOO_URL = "https://errorcorrectionzoo.org/c/";

  var factsCache = typeof WeakMap !== "undefined" ? new WeakMap() : null;
  // Computed facts about a code: { n, k, d, dAtLeast, css, checks,
  // weights: [min, max], rate }.
  function computedFacts(code) {
    if (factsCache && factsCache.has(code)) return factsCache.get(code);
    var a = S.analyzeChecks(code.n, code.stabilizers);
    var ws = code.stabilizers.map(S.weight);
    var f = {
      n: a.n, k: a.k, d: a.d, dAtLeast: a.dAtLeast, css: a.css,
      checks: code.stabilizers.length,
      weights: [Math.min.apply(null, ws), Math.max.apply(null, ws)],
      rate: a.k / a.n
    };
    if (factsCache) factsCache.set(code, f);
    return f;
  }
  function paramsString(f) {
    return "[[" + f.n + "," + f.k + "," + (f.d !== null ? f.d : "≥" + f.dAtLeast) + "]]";
  }
  function list(items) {
    return "<ul>" + items.map(function (t) { return "<li>" + t + "</li>"; }).join("") + "</ul>";
  }
  function logicalLines(code) {
    var k = code.logicalX.length, out = [];
    for (var j = 0; j < k; j++) {
      var sub = k > 1 ? String(j + 1) : "";
      out.push("X̄" + sub + " = " + S.toString(code.logicalX[j]) + ", Z̄" + sub + " = " + S.toString(code.logicalZ[j]));
    }
    return out.join("<br>");
  }

  // species: an entry of ZooData.SPECIES (or any { name, code, placard? }).
  function html(species) {
    var code = species.code, f = computedFacts(code), p = species.placard || {};
    var w = f.weights[0] === f.weights[1] ? String(f.weights[0]) : f.weights[0] + "–" + f.weights[1];
    var rows = [
      ["Parameters", paramsString(f) + " (computed from the checks)"],
      ["Logical qubits", f.k + " (" + (f.k === 1 ? "one animal" : f.k + " animals") + "), rate k/n = " + f.k + "/" + f.n],
      ["Checks", f.checks + " independent, weight " + w],
      ["Type", f.css ? "CSS: generated by pure-X and pure-Z checks" : "Non-CSS: checks mix X and Z"]
    ];
    var out = "";
    if (p.summary) out += "<p>" + p.summary + "</p>";
    out += '<dl class="facts">' + rows.map(function (r) {
      return "<dt>" + r[0] + "</dt><dd>" + r[1] + "</dd>";
    }).join("") + "</dl>";
    if (p.facts && p.facts.length) out += "<h4>Properties</h4>" + list(p.facts);
    if (p.origin) out += "<h4>Origin</h4><p>" + p.origin + "</p>";
    if (p.lab && p.lab.length) out += "<h4>In the lab</h4>" + list(p.lab);
    out += '<div class="ops">Stabilizers: ' + code.stabilizers.map(S.toString).join(", ") +
      "<br>" + logicalLines(code) + "</div>";
    if (p.zoo) {
      out += '<p class="src"><a href="' + ZOO_URL + p.zoo + '" target="_blank" rel="noopener">' +
        "Error Correction Zoo entry ↗</a></p>";
    }
    return out;
  }

  var Placard = { ZOO_URL: ZOO_URL, computedFacts: computedFacts, paramsString: paramsString, html: html };
  if (isNode) module.exports = Placard;
  else root.Placard = Placard;
})(typeof window !== "undefined" ? window : this);
